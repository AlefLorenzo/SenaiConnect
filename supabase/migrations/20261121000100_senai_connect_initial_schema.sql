CREATE OR REPLACE FUNCTION private.handle_new_auth_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_email text;
  v_name text;
  v_role text;
  v_existing boolean;
begin
  if new.id is null or new.email is null then
    raise exception 'A conta precisa ter UUID e e-mail.';
  end if;

  v_email := lower(trim(new.email));
  select exists(select 1 from public.users u where lower(u.email) = v_email) into v_existing;

  if not v_existing
     and v_email not like '%@estudante.senai.com'
     and v_email not like '%@docente.senai.com' then
    raise exception 'Use um e-mail institucional SENAI para criar uma conta.';
  end if;

  v_name := coalesce(
    nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
    nullif(trim(new.raw_user_meta_data ->> 'name'), ''),
    split_part(v_email, '@', 1)
  );
  v_role := case
    when v_email like '%@docente.senai.com' then 'Professor'
    else 'Aluno'
  end;

  insert into public.users as existing_profile
    (name,email,role,password_hash,auth_user_id)
  values
    (v_name,v_email,v_role,null,new.id)
  on conflict (email) do update
    set auth_user_id = coalesce(existing_profile.auth_user_id, excluded.auth_user_id),
        name = case when existing_profile.name is null or existing_profile.name = '' then excluded.name else existing_profile.name end
    where existing_profile.auth_user_id is null
       or existing_profile.auth_user_id = excluded.auth_user_id;

  return new;
end;
$function$


CREATE OR REPLACE FUNCTION private.is_current_user_profile(target_user_id bigint)
 RETURNS boolean
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
  select exists(
    select 1 from public.users u
    where u.id = target_user_id
      and u.auth_user_id = (select auth.uid())
  );
$function$


